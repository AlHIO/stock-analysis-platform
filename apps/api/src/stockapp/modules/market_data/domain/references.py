"""Read-only reference boundary for business modules; no persistence imports."""
from datetime import date
from typing import Protocol
from uuid import UUID

from .models import TradingCalendar
from .runtime import RuntimeRun


class MarketReferenceReader(Protocol):
    def instrument(self, instrument_id: UUID) -> dict | None: ...
    def source(self, source_id: UUID) -> dict | None: ...
    def source_by_code(self, code: str) -> dict | None: ...
    def market_by_code(self, code: str) -> dict | None: ...
    def calendar(self, market_id: UUID, start: date, end: date) -> tuple[TradingCalendar, ...]: ...
    def latest_run(self, source_id: UUID, *, status: str | None = None) -> RuntimeRun | None: ...
    def ingestion_freshness(self, source_code: str) -> dict: ...
