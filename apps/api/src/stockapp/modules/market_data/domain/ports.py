"""Synchronous repository contracts; the caller owns the transaction boundary.

Implementations must not commit implicitly. A DailyBar upsert persists both the
normalized observation and the canonical snapshot atomically in that transaction.
"""

from datetime import date
from typing import Protocol
from uuid import UUID

from stockapp.modules.market_data.domain.models import (
    DailyBar,
    DataSource,
    IngestionRun,
    Instrument,
    Market,
    TradingCalendar,
)


class MarketRepository(Protocol):
    def add(self, market: Market) -> Market: ...
    def get(self, id: UUID) -> Market | None: ...
    def get_by_code(self, code: str) -> Market | None: ...


class InstrumentRepository(Protocol):
    def add(self, instrument: Instrument) -> Instrument: ...
    def update_metadata(self, instrument: Instrument) -> Instrument: ...
    def get(self, id: UUID) -> Instrument | None: ...
    def get_by_symbol(self, market_id: UUID, symbol: str) -> Instrument | None: ...


class TradingCalendarRepository(Protocol):
    def upsert(self, calendar: TradingCalendar) -> TradingCalendar: ...
    def get(self, market_id: UUID, trade_date: date) -> TradingCalendar | None: ...


class DailyBarRepository(Protocol):
    def upsert(self, bar: DailyBar) -> DailyBar: ...
    def get(self, instrument_id: UUID, trade_date: date) -> DailyBar | None: ...
    def list_for_instrument(
        self, instrument_id: UUID, *, start: date | None = None, end: date | None = None
    ) -> list[DailyBar]: ...
    def list_revisions(self, instrument_id: UUID, trade_date: date) -> list[DailyBar]: ...


class DataSourceRepository(Protocol):
    def add(self, source: DataSource) -> DataSource: ...
    def get(self, id: UUID) -> DataSource | None: ...
    def get_by_code(self, code: str) -> DataSource | None: ...


class IngestionRunRepository(Protocol):
    def add(self, run: IngestionRun) -> IngestionRun: ...
    def update(self, run: IngestionRun) -> IngestionRun: ...
    def get(self, id: UUID) -> IngestionRun | None: ...
